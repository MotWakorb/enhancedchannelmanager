MCP_ALLOWED_ROUTES: frozenset[tuple[str, str]] = (
    _MCP_DECLARED_ROUTES - MCP_HUMAN_ONLY_ROUTES
)


def is_mcp_route_allowed(method: str, route_template: str | None) -> bool:
    """Return the explicit service-principal verdict; unknown means denied."""
    if route_template is None:
        return False
    return (method.upper(), route_template) in MCP_ALLOWED_ROUTES
