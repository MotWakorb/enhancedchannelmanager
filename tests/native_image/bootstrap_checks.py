"""Validate only a gate-owned fresh config volume; never print secret contents."""

import argparse
import hashlib
import json
import os
import stat
import sys
import urllib.request
from pathlib import Path


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--uid", type=int, required=True)
    parser.add_argument("--gid", type=int, required=True)
    parser.add_argument("--phase", choices=("create", "verify"), required=True)
    parser.add_argument("--marker", required=True)
    args = parser.parse_args()
    assert sys.prefix == "/opt/venv", "not running the image virtualenv"
    assert (os.getuid(), os.getgid()) == (args.uid, args.gid), "exec identity mismatch"
    status = dict(
        line.split(":", 1)
        for line in Path("/proc/1/status").read_text().splitlines()
        if ":" in line
    )
    assert [int(value) for value in status["Uid"].split()] == [args.uid] * 4, (
        "PID 1 UID mismatch"
    )
    assert [int(value) for value in status["Gid"].split()] == [args.gid] * 4, (
        "PID 1 GID mismatch"
    )
    runtime = Path("/run/ecm").stat()
    assert (runtime.st_uid, runtime.st_gid, stat.S_IMODE(runtime.st_mode)) == (
        args.uid,
        args.gid,
        0o700,
    )
    # Do not use ambient proxy settings, even for loopback.
    opener = urllib.request.build_opener(urllib.request.ProxyHandler({}))
    with opener.open("http://127.0.0.1:6100/api/health", timeout=3) as response:
        assert response.status == 200
    config = Path("/config")
    settings = config / "settings.json"
    assert settings.is_file(), "real app has not initialized settings"
    settings_stat = settings.stat()
    assert (settings_stat.st_uid, settings_stat.st_gid) == (args.uid, args.gid)
    # Hash secret material for persistence comparison ONLY; no value or digest is
    # emitted. All material is generated by this fresh, network-isolated app.
    data = json.loads(settings.read_text())
    secret = data.get("mcp_api_key")
    assert isinstance(secret, str) and secret, "startup did not generate an API key"
    fingerprint = hashlib.sha256(secret.encode()).hexdigest()
    marker = config / ".native-image-gate.json"
    expected = {"marker": args.marker, "secret_fingerprint": fingerprint}
    if args.phase == "create":
        assert not marker.exists(), "config volume was not fresh"
        marker.write_text(json.dumps(expected))
        marker.chmod(0o600)
    else:
        assert json.loads(marker.read_text()) == expected, (
            "config or generated key did not persist"
        )
    for path in (config, config / "tls", marker):
        info = path.stat()
        assert (info.st_uid, info.st_gid) == (args.uid, args.gid), (
            "config ownership mismatch"
        )
    assert stat.S_IMODE((config / "tls").stat().st_mode) == 0o700
    print(
        json.dumps(
            {"status": "PASS", "uid": args.uid, "gid": args.gid, "phase": args.phase}
        )
    )


if __name__ == "__main__":
    main()
