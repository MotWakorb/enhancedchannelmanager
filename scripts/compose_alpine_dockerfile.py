#!/usr/bin/env python3
"""Compose a self-contained Alpine build from the independently exercised recipes.

No compiler/package/source logic is duplicated. The generated Dockerfile needs
only the repository context, not a CI artifact or manually prepared named input.
This is build integration, not security clearance or production publication.
"""

from __future__ import annotations

import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = "Dockerfile"
COMPONENTS = (
    "docker/alpine-native/Dockerfile.inputs",
    "docker/alpine-native/Dockerfile.codecs",
    "docker/alpine-native/Dockerfile.security-libraries",
    "docker/alpine-native/Dockerfile.libjxl",
    "docker/alpine-native/Dockerfile.ffmpeg",
    "docker/alpine-native/Dockerfile.gosu",
    "docker/alpine-native/Dockerfile.resdet",
    "docker/alpine-native/Dockerfile.packages",
    "docker/alpine-busybox/Dockerfile",
)
CANDIDATE = "docker/alpine-native/Dockerfile.candidate"


def render(root: Path) -> str:
    parts = [
        "# Generated by scripts/compose_alpine_dockerfile.py; do not hand-edit.\n"
        "# Self-contained stable Alpine image; source/advisory scope remains pending."
    ]
    parts.extend((root / relative).read_text().strip() for relative in COMPONENTS)
    parts.append(
        "# Resolve the candidate's last two input contexts from this build graph.\n"
        "FROM package-evidence AS native-packages\n"
        "FROM busybox-evidence AS busybox-packages"
    )
    # Keep the proven integration recipe byte-for-byte; its input context names
    # now resolve to previous scratch stages rather than caller-supplied paths.
    parts.append((root / CANDIDATE).read_text().rstrip("\n"))
    parts.append("COPY Dockerfile /usr/share/ecm/sources/trust/Dockerfile")
    return "\n\n".join(parts) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args(argv)
    expected = render(ROOT)
    target = ROOT / OUTPUT
    if args.check:
        if not target.is_file() or target.read_text() != expected:
            parser.exit(1, f"{OUTPUT} is stale; run {Path(__file__).name}\n")
    else:
        target.write_text(expected)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
